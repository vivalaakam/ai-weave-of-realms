const EMPTY_TILE: u32 = u32::MAX;

// Unified tile atlas embedded at compile time.
// Format: b"RPGT" + u8 tile_w + u8 tile_h + u32 count LE, then count × mask_bytes.
// Generated by: cargo run -p rpg-tools --bin pack-tiles
const TILES_BIN: &[u8] = include_bytes!("../../../assets/tiles.bin");
const ATLAS_HEADER: usize = 10; // 4 magic + 1 w + 1 h + 4 count LE

const TILESET_TILE_W: usize = 16;
const TILESET_TILE_H: usize = 16;
const TILESET_MASK_BYTES: usize = (TILESET_TILE_W * TILESET_TILE_H).div_ceil(8);

// Grass tile indices within the atlas (tiles 5, 6, 7 from monochrome-transparent_packed.png).
const GRASS_INDICES: [usize; 3] = [5, 6, 7];
const GRASS_TILE_COUNT: usize = GRASS_INDICES.len();

const FOREST_INDICES: [usize; 6] = [49, 50, 51, 52, 53, 54];
const FOREST_TILE_COUNT: usize = FOREST_INDICES.len();

// Water tile indices from 2_water.png (5 tiles at 1078..1082).
const WATER_BASE: usize = 1078;
const WATER_FULL: usize = WATER_BASE; // tile 0: full water rectangle
const WATER_SHORE_LL: usize = WATER_BASE + 1; // tile 1: shore, lower-left half of W edge
const WATER_CORNER_OUTER: usize = WATER_BASE + 3; // tile 3: outer corner, upper-left
const WATER_CORNER_INNER: usize = WATER_BASE + 4; // tile 4: inner corner, upper-left

// Mountain tile indices from 3_mountains.png (5 tiles at 1083..1087).
const MOUNTAIN_BASE: usize = 1083;
const MOUNTAIN_FULL: usize = MOUNTAIN_BASE;
const MOUNTAIN_SHORE_LL: usize = MOUNTAIN_BASE + 1;
const MOUNTAIN_CORNER_OUTER: usize = MOUNTAIN_BASE + 3;
const MOUNTAIN_CORNER_INNER: usize = MOUNTAIN_BASE + 4;

type WaterMask = [u8; TILESET_MASK_BYTES];

const TILE_WIDTH: u32 = 32;
const TILE_HEIGHT: u32 = 32;

fn tile_atlas_mask(tile_idx: usize) -> &'static [u8] {
    let start = ATLAS_HEADER + tile_idx * TILESET_MASK_BYTES;
    &TILES_BIN[start..start + TILESET_MASK_BYTES]
}

fn grass_mask(grass_idx: usize) -> &'static [u8] {
    tile_atlas_mask(GRASS_INDICES[grass_idx])
}

fn forest_mask(forest_idx: usize) -> &'static [u8] {
    tile_atlas_mask(FOREST_INDICES[forest_idx])
}

fn get_tile_mask_arr(idx: usize) -> WaterMask {
    let mut arr = [0u8; TILESET_MASK_BYTES];
    arr.copy_from_slice(tile_atlas_mask(idx));
    arr
}

fn mask_pixel_arr(m: &WaterMask, x: usize, y: usize) -> bool {
    let bit = y * TILESET_TILE_W + x;
    (m[bit / 8] >> (7 - bit % 8)) & 1 != 0
}

fn rotate_cw90(m: &WaterMask) -> WaterMask {
    // pixel (x, y) → (N-1-y, x) where N = TILESET_TILE_W = 16
    let n = TILESET_TILE_W;
    let mut out = [0u8; TILESET_MASK_BYTES];
    for y in 0..n {
        for x in 0..n {
            if mask_pixel_arr(m, x, y) {
                let nx = n - 1 - y;
                let ny = x;
                let bit = ny * n + nx;
                out[bit / 8] |= 1 << (7 - bit % 8);
            }
        }
    }
    out
}

fn and_mask(mut a: WaterMask, b: &WaterMask) -> WaterMask {
    for i in 0..TILESET_MASK_BYTES {
        a[i] &= b[i];
    }
    a
}

// Neighbor bits: bit0=N, bit1=NE, bit2=E, bit3=SE, bit4=S, bit5=SW, bit6=W, bit7=NW
// 1 = neighbor is water, 0 = neighbor is land or out-of-bounds
/// Computes 8-neighbor bitmask for terrain autotiling.
/// Bits (0..7) = N, NE, E, SE, S, SW, W, NW; bit=1 means neighbor matches `target`.
fn terrain_neighbor_bits(
    map: &engine::map::game_map::GameMap,
    coord: MapCoord,
    target: engine::map::tile::Tiles,
) -> u8 {
    let matcher = |cx: i32, cy: i32| -> bool {
        if cx < 0 || cy < 0 {
            return false;
        }
        let c = MapCoord::new(cx as u32, cy as u32);
        map.get_tile(c).is_ok_and(|t| t.kind == target)
    };
    let x = coord.x as i32;
    let y = coord.y as i32;
    let n = matcher(x, y - 1) as u8;
    let ne = matcher(x + 1, y - 1) as u8;
    let e = matcher(x + 1, y) as u8;
    let se = matcher(x + 1, y + 1) as u8;
    let s = matcher(x, y + 1) as u8;
    let sw = matcher(x - 1, y + 1) as u8;
    let w = matcher(x - 1, y) as u8;
    let nw = matcher(x - 1, y - 1) as u8;
    n | (ne << 1) | (e << 2) | (se << 3) | (s << 4) | (sw << 5) | (w << 6) | (nw << 7)
}

/// Autotile composite mask: `bits` describes neighbors matching the terrain.
/// `land()` returns true when the neighbor does *not* match (== land).
fn compute_terrain_composite(
    bits: u8,
    full_tile: usize,
    shore_ll: usize,
    corner_outer: usize,
    corner_inner: usize,
) -> WaterMask {
    let land = |bit: u8| (bits & bit) == 0;
    let n = land(0x01);
    let ne = land(0x02);
    let e = land(0x04);
    let se = land(0x08);
    let s = land(0x10);
    let sw = land(0x20);
    let w = land(0x40);
    let nw = land(0x80);

    let ll = get_tile_mask_arr(shore_ll);
    let ul = get_tile_mask_arr(shore_ll + 1);
    let co = get_tile_mask_arr(corner_outer);
    let ci = get_tile_mask_arr(corner_inner);
    let ll90 = rotate_cw90(&ll);
    let ll180 = rotate_cw90(&ll90);
    let ll270 = rotate_cw90(&ll180);
    let ul90 = rotate_cw90(&ul);
    let ul180 = rotate_cw90(&ul90);
    let ul270 = rotate_cw90(&ul180);
    let co90 = rotate_cw90(&co);
    let co180 = rotate_cw90(&co90);
    let co270 = rotate_cw90(&co180);
    let ci90 = rotate_cw90(&ci);
    let ci180 = rotate_cw90(&ci90);
    let ci270 = rotate_cw90(&ci180);

    let mut mask = get_tile_mask_arr(full_tile);

    // Edge half-pieces
    if w && !n {
        mask = and_mask(mask, &ul);
    }
    if w && !s {
        mask = and_mask(mask, &ll);
    }
    if n && !w {
        mask = and_mask(mask, &ll90);
    }
    if n && !e {
        mask = and_mask(mask, &ul90);
    }
    if e && !n {
        mask = and_mask(mask, &ll180);
    }
    if e && !s {
        mask = and_mask(mask, &ul180);
    }
    if s && !w {
        mask = and_mask(mask, &ul270);
    }
    if s && !e {
        mask = and_mask(mask, &ll270);
    }

    // Outer corners
    if w && n {
        mask = and_mask(mask, &co);
    }
    if n && e {
        mask = and_mask(mask, &co90);
    }
    if e && s {
        mask = and_mask(mask, &co180);
    }
    if s && w {
        mask = and_mask(mask, &co270);
    }

    // Inner corners
    if !w && !n && nw {
        mask = and_mask(mask, &ci);
    }
    if !n && !e && ne {
        mask = and_mask(mask, &ci90);
    }
    if !e && !s && se {
        mask = and_mask(mask, &ci180);
    }
    if !s && !w && sw {
        mask = and_mask(mask, &ci270);
    }

    mask
}

fn water_neighbor_bits(map: &engine::map::game_map::GameMap, coord: MapCoord) -> u8 {
    terrain_neighbor_bits(map, coord, Tiles::Water)
}

fn compute_water_composite(bits: u8) -> WaterMask {
    compute_terrain_composite(
        bits,
        WATER_FULL,
        WATER_SHORE_LL,
        WATER_CORNER_OUTER,
        WATER_CORNER_INNER,
    )
}

fn mountain_neighbor_bits(map: &engine::map::game_map::GameMap, coord: MapCoord) -> u8 {
    terrain_neighbor_bits(map, coord, Tiles::Mountain)
}

fn compute_mountain_composite(bits: u8) -> WaterMask {
    compute_terrain_composite(
        bits,
        MOUNTAIN_FULL,
        MOUNTAIN_SHORE_LL,
        MOUNTAIN_CORNER_OUTER,
        MOUNTAIN_CORNER_INNER,
    )
}
fn mask_pixel(mask: &[u8], x: usize, y: usize) -> bool {
    let bit = y * TILESET_TILE_W + x;
    (mask[bit / 8] >> (7 - bit % 8)) & 1 != 0
}

fn draw_grass_sprite<D, C>(display: &mut D, top_left: Point, mask: &[u8], color: C)
where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let mut pixels = vec![];
    for src_y in 0..TILESET_TILE_H {
        let dy_start = (src_y * TILE_HEIGHT as usize / TILESET_TILE_H) as i32;
        let dy_end = ((src_y + 1) * TILE_HEIGHT as usize / TILESET_TILE_H) as i32;
        for src_x in 0..TILESET_TILE_W {
            if !mask_pixel(mask, src_x, src_y) {
                continue;
            }
            let dx_start = (src_x * TILE_WIDTH as usize / TILESET_TILE_W) as i32;
            let dx_end = ((src_x + 1) * TILE_WIDTH as usize / TILESET_TILE_W) as i32;
            for dy in dy_start..dy_end {
                for dx in dx_start..dx_end {
                    pixels.push(Pixel(top_left + Point::new(dx, dy), color));
                }
            }
        }
    }
    halt_on_error(display.draw_iter(pixels));
}

