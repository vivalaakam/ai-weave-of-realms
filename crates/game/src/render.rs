/// Draws the shared gameplay map view.
///
/// # Arguments
/// * `display` - Platform draw target.
/// * `screen_size` - Full drawable screen size in pixels.
/// * `map_view` - Shared gameplay state.
/// * `render_cache` - Incremental render cache.
/// * `config` - Geometry settings for the device.
/// * `theme` - Device-specific colors.
pub fn draw_map_view<D, C>(
    display: &mut D,
    screen_size: Size,
    map_view: &MapViewApp,
    render_cache: &mut RenderCache,
    config: RenderConfig,
    theme: MapViewTheme<C>,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let text_style = MonoTextStyle::new(&FONT_6X10, theme.text);
    let header = map_view.session().summary();
    let origin_x = 0i32;
    let origin_y = config.header_height as i32;
    let (visible_cols, visible_rows) = visible_tiles(screen_size, config);
    let map = &map_view.session().state().map;
    let map_width = map.tile_width() as usize;
    let map_height = map.tile_height() as usize;

    let requires_full_redraw = match render_cache.map_view.as_ref() {
        Some(cache) => {
            cache.map_name != map_view.session().map_name()
                || cache.map_width != map_width
                || cache.map_height != map_height
                || cache.visible_cols != visible_cols
                || cache.visible_rows != visible_rows
                || cache.view_x != map_view.view_x()
                || cache.view_y != map_view.view_y()
                || cache.cursor_x != map_view.cursor_x()
                || cache.cursor_y != map_view.cursor_y()
        }
        None => true,
    };

    if requires_full_redraw {
        halt_on_error(display.clear(theme.background));
        render_cache.map_view = Some(MapViewCache {
            map_name: map_view.session().map_name().to_string(),
            map_width,
            map_height,
            visible_cols,
            visible_rows,
            view_x: map_view.view_x(),
            view_y: map_view.view_y(),
            cursor_x: map_view.cursor_x(),
            cursor_y: map_view.cursor_y(),
            visible_cells: vec![EMPTY_TILE; visible_cols * visible_rows],
        });
    }

    let cache = render_cache.map_view.as_mut().expect("map view cache must exist before drawing");

    clear_band(
        display,
        Rectangle::new(Point::new(0, 0), Size::new(screen_size.width, config.header_height)),
        theme.background,
    );
    halt_on_error(
        Text::new(&header, Point::new(4, config.header_height as i32 - 2), text_style)
            .draw(display),
    );

    for row in 0..visible_rows {
        for col in 0..visible_cols {
            let map_x = map_view.view_x() + col;
            let map_y = map_view.view_y() + row;
            let coord = MapCoord::new(map_x as u32, map_y as u32);
            let cell = if map_x < map_width && map_y < map_height {
                cell_signature(map_view, coord)
            } else {
                EMPTY_TILE
            };
            let cache_index = row * visible_cols + col;
            if cache.visible_cells[cache_index] == cell {
                continue;
            }

            cache.visible_cells[cache_index] = cell;
            let x = origin_x + (col as i32 * TILE_WIDTH as i32);
            let y = origin_y + (row as i32 * TILE_HEIGHT as i32);
            draw_cell(
                display,
                map_view,
                coord,
                Point::new(x, y),
                &mut render_cache.water_masks,
                &mut render_cache.mountain_masks,
                theme,
            );
        }
    }

    // Draw cursor highlight.
    if map_view.cursor_structure().is_some() {
        draw_cursor_rect(display, map_view, config, theme, origin_x, origin_y);
    } else {
        draw_cursor_outline(display, map_view, config, theme, origin_x, origin_y);
    }

    clear_band(
        display,
        Rectangle::new(
            Point::new(0, screen_size.height as i32 - config.footer_height as i32),
            Size::new(screen_size.width, config.footer_height),
        ),
        theme.background,
    );
}

fn draw_cell<D, C>(
    display: &mut D,
    map_view: &MapViewApp,
    coord: MapCoord,
    top_left: Point,
    water_masks: &mut Vec<Option<WaterMask>>,
    mountain_masks: &mut Vec<Option<WaterMask>>,
    theme: MapViewTheme<C>,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let map = &map_view.session().state().map;
    let Ok(tile) = map.get_tile(coord) else {
        return;
    };

    let sprite_w = TILE_WIDTH.saturating_sub(1);
    let sprite_h = TILE_HEIGHT.saturating_sub(1);
    halt_on_error(
        Rectangle::new(top_left, Size::new(sprite_w, sprite_h))
            .into_styled(PrimitiveStyle::with_fill((theme.tile_color)(tile.kind)))
            .draw(display),
    );

    if matches!(tile.kind, Tiles::Meadow) {
        let grass_idx = (coord.x as usize * 31 + coord.y as usize * 17) % GRASS_TILE_COUNT;
        draw_grass_sprite(
            display,
            top_left,
            grass_mask(grass_idx),
            (theme.tile_sprite_color)(tile.kind),
        );
    }

    if matches!(tile.kind, Tiles::Forest) {
        let forest_idx = (coord.x as usize * 31 + coord.y as usize * 17) % FOREST_TILE_COUNT;
        draw_grass_sprite(
            display,
            top_left,
            forest_mask(forest_idx),
            (theme.tile_sprite_color)(tile.kind),
        );
    }

    if matches!(tile.kind, Tiles::Water) {
        draw_water_cell(display, map, coord, top_left, water_masks, theme);
    }

    if matches!(tile.kind, Tiles::Mountain) {
        draw_mountain_cell(display, map, coord, top_left, mountain_masks, theme);
    }

    if let Some(team_id) = map_view.session().state().city_owner(coord) {
        halt_on_error(
            Rectangle::new(top_left + Point::new(1, 1), Size::new(4, 4))
                .into_styled(PrimitiveStyle::with_fill((theme.team_color)(team_id as usize)))
                .draw(display),
        );
    }

    if map.has_enemy_spawn(coord) {
        halt_on_error(
            Rectangle::new(top_left + Point::new(1, 1), Size::new(3, 3))
                .into_styled(PrimitiveStyle::with_fill(theme.enemy_spawn))
                .draw(display),
        );
    }

    if map.has_chest_spawn(coord) {
        let x = top_left.x + TILE_WIDTH as i32 - 5;
        halt_on_error(
            Rectangle::new(Point::new(x, top_left.y + 1), Size::new(3, 3))
                .into_styled(PrimitiveStyle::with_fill(theme.chest))
                .draw(display),
        );
    }

    if let Some(hero) = map_view.session().state().hero_at(coord) {
        draw_hero_marker(
            display,
            hero.get_id(),
            map_view.session().selected_hero_id(),
            top_left,
            theme,
        );
    }
}

fn draw_water_cell<D, C>(
    display: &mut D,
    map: &engine::map::game_map::GameMap,
    coord: MapCoord,
    top_left: Point,
    water_masks: &mut Vec<Option<WaterMask>>,
    theme: MapViewTheme<C>,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let bits = water_neighbor_bits(map, coord);
    let mask = cached_water_mask(water_masks, bits);
    draw_grass_sprite(display, top_left, &mask, (theme.tile_sprite_color)(Tiles::Water));
}

fn draw_mountain_cell<D, C>(
    display: &mut D,
    map: &engine::map::game_map::GameMap,
    coord: MapCoord,
    top_left: Point,
    mountain_masks: &mut Vec<Option<WaterMask>>,
    theme: MapViewTheme<C>,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let bits = mountain_neighbor_bits(map, coord);
    let mask = cached_mountain_mask(mountain_masks, bits);
    draw_grass_sprite(display, top_left, &mask, (theme.tile_sprite_color)(Tiles::Mountain));
}

fn draw_hero_marker<D, C>(
    display: &mut D,
    hero_id: HeroId,
    selected_hero_id: HeroId,
    top_left: Point,
    theme: MapViewTheme<C>,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let color = if hero_id == selected_hero_id { theme.selected_hero } else { theme.hero };
    let mask = tile_atlas_mask(25);
    draw_grass_sprite(display, top_left, mask, color);
}

fn draw_cursor_outline<D, C>(
    display: &mut D,
    map_view: &MapViewApp,
    _config: RenderConfig,
    theme: MapViewTheme<C>,
    origin_x: i32,
    origin_y: i32,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let cursor_x = map_view.cursor_x();
    let cursor_y = map_view.cursor_y();
    let view_x = map_view.view_x() as isize;
    let view_y = map_view.view_y() as isize;
    let rel_x = cursor_x - view_x;
    let rel_y = cursor_y - view_y;
    if rel_x < 0 || rel_y < 0 {
        return;
    }
    let x = origin_x + (rel_x as i32) * TILE_WIDTH as i32;
    let y = origin_y + (rel_y as i32) * TILE_HEIGHT as i32;
    draw_rect_stroke(display, x, y, TILE_WIDTH, TILE_HEIGHT, theme.cursor);
}

fn draw_cursor_rect<D, C>(
    display: &mut D,
    map_view: &MapViewApp,
    _config: RenderConfig,
    theme: MapViewTheme<C>,
    origin_x: i32,
    origin_y: i32,
) where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    if let Some(info) = map_view.cursor_structure() {
        let view_x = map_view.view_x() as isize;
        let view_y = map_view.view_y() as isize;
        let start_x = (info.min_x as isize - view_x) as i32;
        let start_y = (info.min_y as isize - view_y) as i32;
        let end_x = start_x + (info.max_x - info.min_x + 1) as i32;
        let end_y = start_y + (info.max_y - info.min_y + 1) as i32;

        // visible area in tiles
        let visible_cols = 1000i32; // will be clamped by screen below
        let visible_rows = 1000i32;

        if end_x <= 0 || end_y <= 0 || start_x >= visible_cols || start_y >= visible_rows {
            return;
        }

        let clamped_start_x = start_x.max(0);
        let clamped_start_y = start_y.max(0);
        let clamped_end_x = (end_x as i32).min(visible_cols);
        let clamped_end_y = (end_y as i32).min(visible_rows);

        let width = ((clamped_end_x - clamped_start_x).max(0) as u32) * TILE_WIDTH;
        let height = ((clamped_end_y - clamped_start_y).max(0) as u32) * TILE_HEIGHT;

        let x = origin_x + clamped_start_x * TILE_WIDTH as i32;
        let y = origin_y + clamped_start_y * TILE_HEIGHT as i32;

        if width > 0 && height > 0 {
            draw_rect_stroke(display, x, y, width, height, theme.cursor);
        }
    }
}

fn draw_rect_stroke<D, C>(display: &mut D, x: i32, y: i32, width: u32, height: u32, color: C)
where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    let stroke = PrimitiveStyle::with_stroke(color, 2);
    let rect = Rectangle::new(Point::new(x, y), Size::new(width, height)).into_styled(stroke);
    halt_on_error(rect.draw(display));
}

fn cell_signature(map_view: &MapViewApp, coord: MapCoord) -> u32 {
    let map = &map_view.session().state().map;
    let Ok(tile) = map.get_tile(coord) else {
        return EMPTY_TILE;
    };

    let mut signature = tile.kind.to_gid();
    if let Some(hero) = map_view.session().state().hero_at(coord) {
        signature |= (u32::from(hero.get_id()) + 1) << 16;
    }
    if let Some(team_id) = map_view.session().state().city_owner(coord) {
        signature |= (u32::from(team_id) + 1) << 24;
    }
    if map.has_enemy_spawn(coord) {
        signature |= 1 << 30;
    }
    if map.has_chest_spawn(coord) {
        signature |= 1 << 31;
    }
    signature
}

fn clear_band<D, C>(display: &mut D, rect: Rectangle, color: C)
where
    D: DrawTarget<Color = C>,
    C: PixelColor + Copy,
{
    halt_on_error(rect.into_styled(PrimitiveStyle::with_fill(color)).draw(display));
}

fn halt_on_error<T, E>(result: Result<T, E>) -> T {
    match result {
        Ok(value) => value,
        Err(_) => loop {
            core::hint::spin_loop();
        },
    }
}
